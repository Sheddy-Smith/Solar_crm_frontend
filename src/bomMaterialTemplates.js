/**
 * Project BOM templates from physical Malwa Solar B.O.M. FORM sheets.
 * Quantities = Outward (planned requirement), not warehouse stock.
 * Lines with qty 0 stay in template so planners can enable them.
 */

function L(category, name, unit, qty, spec = '') {
  return {
    category,
    material_name: name,
    specification: spec,
    unit: unit || 'Nos',
    qty: Number(qty) || 0,
  };
}

