export function suggestTemplateKey(capacityKwp) {
  const n = Number(capacityKwp) || 0;
  if (n <= 0) return 'other';
  if (n <= 3.5) return '3';
  if (n <= 6) return '5';
  if (n <= 12) return '10';
  return 'other';
}

